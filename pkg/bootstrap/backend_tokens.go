package bootstrap

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
)

// genBackendTokensCmd generates the OPA backend token policy from environment variables.
var genBackendTokensCmd = &cobra.Command{
	Use:   "gen-backend-tokens",
	Short: "Generate OPA backend token policy from environment variables",
	Long: `Reads API tokens from environment variables and writes a Rego policy to
services/opa-backend-token/backend_token.rego, then rebuilds all configs.

Environment variables read:
  ANTHROPIC_TOKEN   Anthropic API token
  GITLAB_TOKEN      GitLab API token
  OPENAI_TOKEN      OpenAI API token
  GITHUB_TOKEN      GitHub API token

Any variable that is unset or empty is omitted from the policy.
At least one token must be set.

Example:
  ANTHROPIC_TOKEN=sk-ant-... cavalier-operator gen-backend-tokens`,
	RunE: runGenBackendTokens,
}

func runGenBackendTokens(cmd *cobra.Command, args []string) error {
	dir := resolveConfigDir()

	providers := []struct{ name, env string }{
	}

	type entry struct{ name, token string }
	var tokens []entry
	for _, p := range providers {
		if tok := os.Getenv(p.env); tok != "" {
			tokens = append(tokens, entry{p.name, tok})
		}
	}

	if len(tokens) == 0 {
		return fmt.Errorf("no tokens found in environment — set at least one of: ANTHROPIC_TOKEN, GITLAB_TOKEN, OPENAI_TOKEN, GITHUB_TOKEN")
	}

	destDir := BackendTokenPolicyDir(dir)
	if err := os.MkdirAll(destDir, 0755); err != nil {
		return fmt.Errorf("creating backend token policy directory: %w", err)
	}

	var lines []string
	lines = append(lines,
		"package backend_token",
		"",
		"# Map of provider name to API token.",
		"# Generated by 'cavalier-operator gen-backend-tokens' — do not edit manually.",
		"tokens := {",
	)
	for _, t := range tokens {
		lines = append(lines, fmt.Sprintf(`    %q: %q,`, t.name, t.token))
	}
	lines = append(lines,
		"}",
		"",
		`default eval := {"token": "", "expires_at_secs": 0}`,
		"",
		`eval := {"token": tok, "expires_at_secs": 0} if {`,
		"    tok := tokens[input.provider]",
		`    tok != ""`,
		"}",
		"",
	)

	regoPath := filepath.Join(destDir, "backend_token.rego")
	if err := os.WriteFile(regoPath, []byte(strings.Join(lines, "\n")), 0600); err != nil {
		return fmt.Errorf("writing backend token policy: %w", err)
	}

	names := make([]string, len(tokens))
	for i, t := range tokens {
		names[i] = t.name
	}
	fmt.Printf("Backend token policy written: %s (%s)\n", regoPath, strings.Join(names, ", "))

	if err := BuildConfigOutput(dir); err != nil {
		return err
	}
	fmt.Printf("Config output: %s/configs/\n", dir)
	return nil
}
