// KernelSourceConfig is the human-editable kernel.yaml source format.
// Per-service configs (sentinel, oauth, gateway) live in separate files.
type KernelSourceConfig struct {
	// Token exchanger settings.
	KeyRotationIntervalSeconds int64 `yaml:"key_rotation_interval_seconds,omitempty"`
	DefaultTokenExpirySeconds  int64 `yaml:"default_token_expiry_seconds,omitempty"`

	// TLS (auto-generated by init)
	TLS *TLSSourceConfig `yaml:"tls,omitempty"`

	// Delegates (added by add-api-key / init cluster)
	Delegates []SourceDelegate `yaml:"delegates,omitempty"`
	Grants    []SourceGrant    `yaml:"grants,omitempty"`
}

// TLSSourceConfig holds base64-encoded TLS cert and key.
type TLSSourceConfig struct {
	Cert string `yaml:"cert"`
	Key  string `yaml:"key"`
}

// SourceDelegate represents a delegate in the source config format.
type SourceDelegate struct {
	Name string `yaml:"name"`
	// TenantNamespace is the canonical authorization namespace of the tenant
	// this delegate's instance belongs to, e.g. "/tenants/acme". Empty — every
	// delegate a shared service gets — means the /system root. Together with
	// Name it is the delegate's key: N tenants' instances of one tenant-owned
	// service all carry the same Name and differ only here.
	TenantNamespace           string                           `yaml:"tenant_namespace,omitempty"`
	AuthorizedServices        []string                         `yaml:"authorized_services,omitempty"`
	KubernetesServiceAccounts []SourceKubernetesServiceAccount `yaml:"kubernetes_service_accounts,omitempty"`
	CustomClaims              map[string]string                `yaml:"custom_claims,omitempty"`
	// AuthBrokerKinds are the classes of user-authentication proof this
	// delegate may broker into kernel's MintUserToken, e.g. "idp". Empty —
	// every delegate but an auth broker — means kernel refuses MintUserToken
	// for it. Round-tripped rather than derived: without this field every
	// rewrite of kernel.yaml below would silently strip a deployment's
	// hand-added broker capability.
	AuthBrokerKinds []string `yaml:"auth_broker_kinds,omitempty"`
}

// SourceKubernetesServiceAccount maps a Kubernetes service account to a
// kernel delegate in the human-editable kernel.yaml source format.
type SourceKubernetesServiceAccount struct {
	KubernetesNamespace      string `yaml:"kubernetes_namespace"`
	KubernetesServiceAccount string `yaml:"kubernetes_service_account"`
}

type SourceGrant struct {
	Id              string                   `yaml:"id"`
	DelegateName    string                   `yaml:"delegate_name"`
	Subject         string                   `yaml:"subject"`
	AuthorizedScope *SourceTokenEntitlements `yaml:"authorized_scope,omitempty"`
	Claims          map[string]any           `yaml:"claims,omitempty"`
	CreatedAtMs     int64                    `yaml:"created_at_ms,omitempty"`
	ExpiresAtMs     int64                    `yaml:"expires_at_ms,omitempty"`
}

type SourceTokenEntitlements struct {
	Grants         []string `yaml:"grants,omitempty"`
	DataGrants     []string `yaml:"data_grants,omitempty"`
	PrincipalScope string   `yaml:"principal_scope,omitempty"`
}

// LoadKernelSourceConfig reads and parses the combined kernel.yaml source file.
func LoadKernelSourceConfig(path string) (*KernelSourceConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading kernel config %q: %w", path, err)
	}
	var cfg KernelSourceConfig
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		return nil, fmt.Errorf("parsing kernel config: %w", err)
	}
	return &cfg, nil
}

func buildTokenEntitlements(src *SourceTokenEntitlements) *protoEntitlements.TokenEntitlements {
	if src == nil {
		return nil
	}
	return &protoEntitlements.TokenEntitlements{
		Grants:         append([]string(nil), src.Grants...),
		DataGrants:     append([]string(nil), src.DataGrants...),
		PrincipalScope: src.PrincipalScope,
	}
}

// AddDelegate reads kernel.yaml, adds/updates a delegate for the given service
// with authorized access to the target service, and writes it back.
// If claims is non-nil, custom claims are set (new delegate) or merged (existing).
func AddDelegate(kernelPath, service, targetService string, claims map[string]string) error {
	cfg, err := LoadKernelSourceConfig(kernelPath)
	if err != nil {
		return fmt.Errorf("loading kernel config: %w", err)
	}

	found := false
	for i, d := range cfg.Delegates {
		if d.Name == service {
			for _, svc := range d.AuthorizedServices {
				if svc == targetService {
					if len(claims) > 0 {
						if cfg.Delegates[i].CustomClaims == nil {
							cfg.Delegates[i].CustomClaims = make(map[string]string)
						}
						for k, v := range claims {
							cfg.Delegates[i].CustomClaims[k] = v
						}
					}
					found = true
					break
				}
			}
			if found {
				break
			}
			cfg.Delegates[i].AuthorizedServices = append(cfg.Delegates[i].AuthorizedServices, targetService)
			if len(claims) > 0 {
				if cfg.Delegates[i].CustomClaims == nil {
					cfg.Delegates[i].CustomClaims = make(map[string]string)
				}
				for k, v := range claims {
					cfg.Delegates[i].CustomClaims[k] = v
				}
			}
			found = true
			break
		}
	}
	if !found {
		cfg.Delegates = append(cfg.Delegates, SourceDelegate{
			Name:               service,
			AuthorizedServices: []string{targetService},
			CustomClaims:       claims,
		})
	}

	data, err := yaml.Marshal(cfg)
	if err != nil {
		return fmt.Errorf("marshaling kernel config: %w", err)
	}
	return os.WriteFile(kernelPath, data, 0644)
}

// WriteServices creates the services/ directory with skeleton config files.
// Existing files are not overwritten.
func WriteServices(cfgDir string) error {
	servicesDir := filepath.Join(cfgDir, "services")
	if err := os.MkdirAll(servicesDir, 0755); err != nil {
		return fmt.Errorf("creating directory: %w", err)
	}

	// Generate TLS cert pair for kernel.yaml
	tlsChain, err := GenerateTLSCertChain()
	if err != nil {
		return fmt.Errorf("generating TLS cert chain: %w", err)
	}

	certB64 := tlsChain.Chain[0].Base64
	keyBytes, err := protoKey.KeyToYAML(tlsChain.Key)
	if err != nil {
		return fmt.Errorf("marshaling TLS key: %w", err)
	}
	keyB64 := base64.StdEncoding.EncodeToString(keyBytes)

	kernelContent := fmt.Sprintf(exampleKernelYAMLTemplate, certB64, keyB64)

	files := map[string]string{
		"kernel.yaml":   kernelContent,
		"sentinel.yaml": exampleSentinelYAML,
		"gateway.yaml":  exampleGatewayYAML,
		"eventbus.yaml": exampleEventbusYAML,
		"oauth.yaml":    exampleOauthYAML,
		"saml.yaml":     exampleSamlYAML,
		"opa.yaml":      exampleOpaYAML,
	}

	for relPath, content := range files {
		absPath := filepath.Join(servicesDir, relPath)
		if _, err := os.Stat(absPath); err == nil {
			fmt.Printf("  (exists, skipped) %s\n", relPath)
			continue
		}
		if err := os.WriteFile(absPath, []byte(content), 0644); err != nil {
			return fmt.Errorf("writing %s: %w", relPath, err)
		}
	}

	return nil
}

// InitOPA generates the OPA entitlements policy directory from the oauth config.
// It reads services/oauth.yaml to extract IDP provider issuers and generates
// trusted_issuer rules that validate the token's origin_iss claim.
// If oauth.yaml does not exist (oauth is disabled), it proceeds with an
// empty issuers list and prints a warning.
func InitOPA(cfgDir string) error {
	opaDir := OPAPolicyDir(cfgDir)

	var issuers []string

	oauthPath := filepath.Join(cfgDir, "services", "oauth.yaml")
	if _, err := os.Stat(oauthPath); err == nil {
		data, err := os.ReadFile(oauthPath)
		if err != nil {
			return fmt.Errorf("reading oauth config: %w", err)
		}

		var fwMap map[string]any
		if err := yaml.Unmarshal(data, &fwMap); err != nil {
			return fmt.Errorf("parsing oauth config: %w", err)
		}

		if providers, ok := fwMap["providers"].([]any); ok {
			for _, p := range providers {
				if pm, ok := p.(map[string]any); ok {
					if iss, ok := pm["issuer"].(string); ok && iss != "" {
						issuers = append(issuers, iss)
					}
				}
			}
		}
	} else {
		fmt.Printf("Warning: %s not found — generating default OPA policy with no trusted issuers.\n", oauthPath)
		fmt.Printf("  Add providers to services/oauth.yaml when oauth is configured and re-run init-opa.\n")
	}

	tenantIdps, err := LoadTenantIdps(cfgDir)
	if err != nil {
		return fmt.Errorf("loading tenant IDP bindings: %w", err)
	}

	if err := WriteDefaultOPAPolicy(opaDir, issuers, tenantIdps); err != nil {
		return fmt.Errorf("writing OPA policy: %w", err)
	}

	fmt.Printf("Generated OPA entitlements policy: %s/\n", opaDir)
	for _, iss := range issuers {
		fmt.Printf("  trusted issuer: %s\n", iss)
	}
	for _, idp := range tenantIdps {
		fmt.Printf("  tenant IDP: (%s, %s) -> %s\n", idp.IssuerURL, idp.ClientID, idp.TenantNamespace)
	}
	fmt.Printf("\nEdit services/opa/idp/claims.rego to customize IDP claim → role mapping.\n")
	fmt.Printf("Run 'schematic-operator generate' to rebuild.\n")
	return nil
}

// BuildKernelConfigProto reads the config directory and assembles the kernel Config proto.
func BuildKernelConfigProto(cfgDir string) (*protoKernel.Config, error) {
	servicesDir := filepath.Join(cfgDir, "services")

	// 1. Load kernel.yaml
	kernelCfg, err := LoadKernelSourceConfig(filepath.Join(servicesDir, "kernel.yaml"))
	if err != nil {
		return nil, err
	}

	opCfg, err := LoadConfig(cfgDir)
	if err != nil {
		opCfg = nil
	}
	kubernetesNamespace := operatorKubernetesNamespace(opCfg)

	// 2. Validate TLS key if present
	if kernelCfg.TLS != nil && kernelCfg.TLS.Key != "" {
		keyYAML, err := base64.StdEncoding.DecodeString(kernelCfg.TLS.Key)
		if err != nil {
			return nil, fmt.Errorf("decoding TLS key: %w", err)
		}
		_, err = protoKey.KeyFromBytes(keyYAML)
		if err != nil {
			return nil, fmt.Errorf("parsing TLS key: %w", err)
		}
	}

	// 3. Build delegates from source config + Kubernetes service-account matchers.
	var delegates []*protoKernel.Delegate
	for _, sd := range kernelCfg.Delegates {
		var authSvcs []protoServices.ServiceName
		for _, s := range sd.AuthorizedServices {
			authSvcs = append(authSvcs, protoServices.ParseServiceNameLiberal(s))
		}
		var brokerKinds []protoTokenRequest.AuthBrokerKind
		for _, k := range sd.AuthBrokerKinds {
			brokerKinds = append(brokerKinds, protoTokenRequest.ParseAuthBrokerKindLiberal(k))
		}
		delegate := &protoKernel.Delegate{
			Name:               sd.Name,
			AuthorizedServices: authSvcs,
			TenantNamespace:    sd.TenantNamespace,
			AuthBrokerKinds:    brokerKinds,
		}
		for _, sa := range sd.KubernetesServiceAccounts {
			appendKubernetesServiceAccountMatcher(delegate, sa.KubernetesNamespace, sa.KubernetesServiceAccount)
		}
		if isKernelAuthenticatedService(sd.Name) {
			inst := ServiceInstance{Service: sd.Name, Tenant: tenantFromNamespace(sd.TenantNamespace)}
			appendKubernetesServiceAccountMatcher(delegate, kubernetesNamespace, delegateServiceAccountName(inst))
		}
		delegates = append(delegates, delegate)
	}

	var grants []*protoKernel.Grant
	for _, sg := range kernelCfg.Grants {
		grant := &protoKernel.Grant{
			Id:              sg.Id,
			DelegateName:    sg.DelegateName,
			Subject:         sg.Subject,
			AuthorizedScope: buildTokenEntitlements(sg.AuthorizedScope),
			CreatedAtMs:     sg.CreatedAtMs,
			ExpiresAtMs:     sg.ExpiresAtMs,
		}
		if len(sg.Claims) > 0 {
			claims, err := structpb.NewStruct(sg.Claims)
			if err != nil {
				return nil, fmt.Errorf("building grant %q claims: %w", sg.Id, err)
			}
			grant.Claims = claims
		}
		grants = append(grants, grant)
	}

	// 4. Load per-service configs from separate files
	holder := &protoServicesConfig.Services{}
	hasHolder := false

	type serviceLoader struct {
		name string
		load func(map[string]any) error
	}
	loaders := []serviceLoader{
		{"sentinel", func(m map[string]any) error {
			cfg := &protoSentinel.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			holder.SentinelConfig = cfg
			hasHolder = true
			return nil
		}},
		{"gateway", func(m map[string]any) error {
			cfg := &protoGateway.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			protoGateway.ConfigDefaults(cfg)
			holder.GatewayConfig = cfg
			hasHolder = true
			return nil
		}},
		{"eventbus", func(m map[string]any) error {
			cfg := &protoEventbus.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			protoEventbus.ConfigDefaults(cfg)
			holder.EventbusConfig = cfg
			hasHolder = true
			return nil
		}},
		{"oauth", func(m map[string]any) error {
			cfg := &protoOauth.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			protoOauth.ConfigDefaults(cfg)
			holder.OauthConfig = cfg
			hasHolder = true
			return nil
		}},
		{"opa", func(m map[string]any) error {
			delete(m, "entitlements_policy")
			delete(m, "backend_token_policy")
			delete(m, "proxy_policy")

			cfg := &protoOpa.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}

			// Load OPA entitlements policy: prefer services/opa/ if present,
			// otherwise generate the default from IDP issuers in oauth.yaml.
			opaDir := OPAPolicyDir(cfgDir)
			if _, err := os.Stat(opaDir); err == nil {
				policy, err := LoadOPAPolicy(opaDir, "data.entitlements.eval")
				if err != nil {
					return fmt.Errorf("loading OPA entitlements policy: %w", err)
				}
				cfg.EntitlementsPolicy = policy
			} else {
				var idpIssuers []string
				oauthPath := filepath.Join(cfgDir, "services", "oauth.yaml")
				if fwData, err := os.ReadFile(oauthPath); err == nil {
					var fwMap map[string]any
					if err := yaml.Unmarshal(fwData, &fwMap); err == nil {
						if providers, ok := fwMap["providers"].([]any); ok {
							for _, p := range providers {
								if pm, ok := p.(map[string]any); ok {
									if iss, ok := pm["issuer"].(string); ok && iss != "" {
										idpIssuers = append(idpIssuers, iss)
									}
								}
							}
						}
					}
				}
				tenantIdps, err := LoadTenantIdps(cfgDir)
				if err != nil {
					return fmt.Errorf("loading tenant IDP bindings: %w", err)
				}
				opaBundle := DefaultOPABundle(idpIssuers, tenantIdps)
				cfg.EntitlementsPolicy = BuildOpaPolicy("data.entitlements.eval", opaBundle)
			}
			if policy, err := LoadOptionalOPAPolicy(ProxyPolicyDir(cfgDir), "data.proxypolicy.eval"); err != nil {
				return fmt.Errorf("loading OPA proxy policy: %w", err)
			} else if policy != nil {
				cfg.ProxyPolicy = policy
			}

			holder.OpaConfig = cfg
			hasHolder = true
			return nil
		}},
	}

	for _, sl := range loaders {
		svcPath := filepath.Join(servicesDir, sl.name+".yaml")
		svcMap, err := loadServiceConfigFile(svcPath)
		if err != nil {
			continue
		}
		if len(svcMap) == 0 {
			svcMap = make(map[string]any)
		}
		if err := sl.load(svcMap); err != nil {
			return nil, fmt.Errorf("parsing %s config: %w", sl.name, err)
		}
	}

	// 5. Load operator-derived FQDN/issuer.
	fqdn := ""
	issuer := ""
	if opCfg != nil {
		fqdn = opCfg.Fqdn
		issuer = Issuer(opCfg)
	}

	// 6. Build kernel Config proto
	// network, logger and rate_limit are assert_required on kernel's Config but
	// carry no message-level default, so ConfigDefaults leaves them nil and
	// kernel rejects the config at boot ("field network is required"). Kernel's
	// own configDefaults does not recurse into submessages either, and the
	// NetworkConfig timeouts are assert_duration POSITIVE, so the scalar
	// defaults have to be filled in here rather than left zero.
	kernelConfig := &protoKernel.Config{
		KeyRotationIntervalSeconds: kernelCfg.KeyRotationIntervalSeconds,
		DefaultTokenExpirySeconds:  kernelCfg.DefaultTokenExpirySeconds,
		Delegates:                  delegates,
		Grants:                     grants,
		Fqdn:                       fqdn,
		Issuer:                     issuer,
		Network:                    &protoHazelcast.NetworkConfig{},
		RateLimit:                  &protoHazelcast.RateLimitConfig{},
		Logger: &protoLogger.LoggerConfig{
			Format:      protoLogger.Format_FORMAT_JSON,
			Level:       protoLogger.Level_LEVEL_DEBUG,
			OutputPaths: []string{"stdout"},
		},
	}
	protoKernel.ConfigDefaults(kernelConfig)
	protoHazelcast.NetworkConfigDefaults(kernelConfig.Network)
	protoHazelcast.RateLimitConfigDefaults(kernelConfig.RateLimit)
	if hasHolder {
		kernelConfig.Configs = holder
	}

	return kernelConfig, nil
}

func operatorKubernetesNamespace(cfg *protoOperator.Config) string {
	if ns := cfg.GetNamespace(); ns != "" {
		return ns
	}
	return "schematic"
}

func appendKubernetesServiceAccountMatcher(delegate *protoKernel.Delegate, namespace, serviceAccount string) {
	if delegate == nil || namespace == "" || serviceAccount == "" {
		return
	}
	for _, existing := range delegate.KubernetesServiceAccounts {
		if existing.GetKubernetesNamespace() == namespace && existing.GetKubernetesServiceAccount() == serviceAccount {
			return
		}
	}
	delegate.KubernetesServiceAccounts = append(delegate.KubernetesServiceAccounts, &protoKernel.KubernetesServiceAccountMatcher{
		KubernetesNamespace:      namespace,
		KubernetesServiceAccount: serviceAccount,
	})
}

// authBrokerKinds are the services that broker a human login into kernel's
// MintUserToken, and the kinds of proof each one is trusted to broker. Kernel
// refuses MintUserToken for a delegate whose auth_broker_kinds does not contain
// the request's kind, so a broker needs the capability on creation or login
// fails closed. Only the broker kind is set here — everything else about who may
// attest a login is still kernel's Delegate record, not this map.
//
// oauth and saml broker an IdP-validated login. personalauth brokers a DEVICE
// proof: a device-held key registering and logging itself in, for a PERSONAL
// principal that has no tenant IdP. It is deliberately NOT given "idp" as well
// — a broker gets exactly the kinds it is built to verify.
var authBrokerKinds = map[string][]string{
	"oauth":        {"idp"},
	"saml":         {"idp"},
	"personalauth": {"device"},
}

// authBrokerKindsFor returns the auth_broker_kinds a newly created delegate for
// svc starts with. Nil for every service that is not an auth broker, which is
// the fail-closed default.
// The slice is copied: the returned value is stored on a delegate that later
// code may append to, and the map's own slice must not be the backing array.
func authBrokerKindsFor(svc string) []string {
	kinds, ok := authBrokerKinds[svc]
	if !ok {
		return nil
	}
	return append([]string(nil), kinds...)
}

// delegateKey is the identity of a kernel delegate: its name plus the
// authorization namespace of the tenant it belongs to. Shared services carry an
// empty namespace, which kernel reads as /system.
type delegateKey struct {
	name            string
	tenantNamespace string
}

// EnsureServiceDelegates ensures kernel.yaml contains a delegate entry for
// every deployed kernel-authenticated service. Each delegate's authorized_services
// is derived from the tacplus registry dependency graph: boundary tags (state/config
// hosting), s2s client dependencies, and event publish/watch broker tags.
// Existing delegates (including user-added ones like oauth API-key delegates)
// are preserved — only missing entries are added or backfilled.
// The function is idempotent: re-running it produces no changes.
func EnsureServiceDelegates(cfgDir string, cfg *protoOperator.Config) error {
	kernelPath := filepath.Join(cfgDir, "services", "kernel.yaml")
	kernelCfg, err := LoadKernelSourceConfig(kernelPath)
	if err != nil {
		return fmt.Errorf("loading kernel config: %w", err)
	}

	// The app's own services are kernel-authenticated too, but they are named
	// only in config, so the registry walk skips them until they are registered.
	// Without this the delegate falls back to the [self, kernel] minimum and an
	// app service that publishes an event gets PermissionDenied against the
	// broker.
	RegisterAppServices(AppServiceNames(cfg))

	sd, err := loadServiceDeps()
	if err != nil {
		return fmt.Errorf("loading service dependencies: %w", err)
	}

	// Keyed by (name, tenant_namespace), not by name alone: a tenant-owned
	// service has one delegate per tenant, all sharing the service's name and
	// differing only in tenant_namespace (kernel's item-2 keying). Keying by
	// name would collapse every tenant's delegate into the first one.
	existing := make(map[delegateKey]int, len(kernelCfg.Delegates))
	for i, d := range kernelCfg.Delegates {
		existing[delegateKey{d.Name, d.TenantNamespace}] = i
	}

	deployed, err := DeployedServiceInstances(cfg)
	if err != nil {
		return fmt.Errorf("resolving deployed service instances: %w", err)
	}
	changed := false

	for _, inst := range deployed {
		svc := inst.Service
		required := sd.authorizedServicesFor(svc)
		if idx, ok := existing[delegateKey{svc, inst.TenantNamespace()}]; ok {
			// Delegate exists — ensure all required services are authorized.
			have := make(map[string]bool, len(kernelCfg.Delegates[idx].AuthorizedServices))
			for _, as := range kernelCfg.Delegates[idx].AuthorizedServices {
				have[as] = true
			}
			for _, req := range required {
				if !have[req] {
					kernelCfg.Delegates[idx].AuthorizedServices = append(kernelCfg.Delegates[idx].AuthorizedServices, req)
					changed = true
				}
			}
			// Backfill the Kubernetes service-account matcher if absent, and
			// resync its namespace if present but stale (idempotent either way).
			//
			// A platform delegate (sentinel, gateway, eventbus, ...) is typically
			// created by the FIRST call to EnsureServiceDelegates, at 'init
			// cluster' time, before operator.yaml's namespace has necessarily been
			// set to its final value. An app_services delegate is often created
			// later, by the 'generate'-time call, once the app's own topology AND
			// the real namespace are both configured — so it picks up the correct
			// namespace on creation while an already-existing platform delegate's
			// matcher was never revisited. Without this resync, every platform
			// delegate stays pinned to whatever namespace (or the "schematic"
			// fallback) was in effect the first time its matcher was written.
			wantNamespace := operatorKubernetesNamespace(cfg)
			wantServiceAccount := delegateServiceAccountName(inst)
			hasKSA := false
			for i, k := range kernelCfg.Delegates[idx].KubernetesServiceAccounts {
				if k.KubernetesServiceAccount != wantServiceAccount {
					continue
				}
				hasKSA = true
				if k.KubernetesNamespace != wantNamespace {
					kernelCfg.Delegates[idx].KubernetesServiceAccounts[i].KubernetesNamespace = wantNamespace
					changed = true
				}
				break
			}
			if !hasKSA {
				kernelCfg.Delegates[idx].KubernetesServiceAccounts = append(
					kernelCfg.Delegates[idx].KubernetesServiceAccounts,
					SourceKubernetesServiceAccount{
						KubernetesNamespace:      wantNamespace,
						KubernetesServiceAccount: wantServiceAccount,
					})
				changed = true
			}
			continue
		}
		// New delegate — authorized_services derived from the registry
		// dependency graph. Fail-closed: only declared deps, never
		// SERVICE_NAME_ANY.
		kernelCfg.Delegates = append(kernelCfg.Delegates, SourceDelegate{
			Name:               svc,
			TenantNamespace:    inst.TenantNamespace(),
			AuthorizedServices: required,
			KubernetesServiceAccounts: []SourceKubernetesServiceAccount{{
				KubernetesNamespace:      operatorKubernetesNamespace(cfg),
				KubernetesServiceAccount: delegateServiceAccountName(inst),
			}},
			AuthBrokerKinds: authBrokerKindsFor(svc),
		})
		existing[delegateKey{svc, inst.TenantNamespace()}] = len(kernelCfg.Delegates) - 1
		changed = true
	}

	if !changed {
		return nil
	}

	data, err := yaml.Marshal(kernelCfg)
	if err != nil {
		return fmt.Errorf("marshaling kernel config: %w", err)
	}
	return os.WriteFile(kernelPath, data, 0644)
}

// loadServiceConfigFile reads a per-service YAML config file into a map.
func loadServiceConfigFile(path string) (map[string]any, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var m map[string]any
	if err := yaml.Unmarshal(data, &m); err != nil {
		return nil, err
	}
	return m, nil
}

// unmarshalMapToProto converts a map[string]any to a proto message via JSON intermediate.
func unmarshalMapToProto(m map[string]any, target proto.Message) error {
	jsonBytes, err := json.Marshal(m)
	if err != nil {
		return fmt.Errorf("converting to JSON: %w", err)
	}
	if err := (protojson.UnmarshalOptions{DiscardUnknown: true}).Unmarshal(jsonBytes, target); err != nil {
		return fmt.Errorf("unmarshaling proto: %w", err)
	}
	return nil
}

// splitLines splits s by newlines and trims whitespace from each line.
func splitLines(s string) []string {
	return strings.Split(strings.TrimSpace(s), "\n")
}

// splitPath splits a path string by "/" separators.
func splitPath(s string) []string {
	return strings.Split(s, "/")
}

