// KernelSourceConfig is the human-editable kernel.yaml source format.
// Per-service configs (sentinel, oauth, gateway) live in separate files.
type KernelSourceConfig struct {
	// Token exchanger settings.
	KeyRotationIntervalSeconds int64 `yaml:"key_rotation_interval_seconds,omitempty"`
	DefaultTokenExpirySeconds  int64 `yaml:"default_token_expiry_seconds,omitempty"`

	// TLS (auto-generated by init)
	TLS *TLSSourceConfig `yaml:"tls,omitempty"`

	// Delegates (added by add-api-key / init cluster)
	Delegates []SourceDelegate `yaml:"delegates,omitempty"`
}

// TLSSourceConfig holds base64-encoded TLS cert and key.
type TLSSourceConfig struct {
	Cert string `yaml:"cert"`
	Key  string `yaml:"key"`
}

// SourceDelegate represents a delegate in the source config format.
type SourceDelegate struct {
	Name               string            `yaml:"name"`
	AuthorizedServices []string          `yaml:"authorized_services,omitempty"`
	CustomClaims       map[string]string `yaml:"custom_claims,omitempty"`
}

// LoadKernelSourceConfig reads and parses the combined kernel.yaml source file.
func LoadKernelSourceConfig(path string) (*KernelSourceConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading kernel config %q: %w", path, err)
	}
	var cfg KernelSourceConfig
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		return nil, fmt.Errorf("parsing kernel config: %w", err)
	}
	return &cfg, nil
}

// AddDelegate reads kernel.yaml, adds/updates a delegate for the given service
// with authorized access to the target service, and writes it back.
// If claims is non-nil, custom claims are set (new delegate) or merged (existing).
func AddDelegate(kernelPath, service, targetService string, claims map[string]string) error {
	cfg, err := LoadKernelSourceConfig(kernelPath)
	if err != nil {
		return fmt.Errorf("loading kernel config: %w", err)
	}

	found := false
	for i, d := range cfg.Delegates {
		if d.Name == service {
			for _, svc := range d.AuthorizedServices {
				if svc == targetService {
					if len(claims) > 0 {
						if cfg.Delegates[i].CustomClaims == nil {
							cfg.Delegates[i].CustomClaims = make(map[string]string)
						}
						for k, v := range claims {
							cfg.Delegates[i].CustomClaims[k] = v
						}
					}
					found = true
					break
				}
			}
			if found {
				break
			}
			cfg.Delegates[i].AuthorizedServices = append(cfg.Delegates[i].AuthorizedServices, targetService)
			if len(claims) > 0 {
				if cfg.Delegates[i].CustomClaims == nil {
					cfg.Delegates[i].CustomClaims = make(map[string]string)
				}
				for k, v := range claims {
					cfg.Delegates[i].CustomClaims[k] = v
				}
			}
			found = true
			break
		}
	}
	if !found {
		cfg.Delegates = append(cfg.Delegates, SourceDelegate{
			Name:               service,
			AuthorizedServices: []string{targetService},
			CustomClaims:       claims,
		})
	}

	data, err := yaml.Marshal(cfg)
	if err != nil {
		return fmt.Errorf("marshaling kernel config: %w", err)
	}
	return os.WriteFile(kernelPath, data, 0644)
}

// WriteServices creates the services/ directory with skeleton config files.
// Existing files are not overwritten.
func WriteServices(cfgDir string) error {
	servicesDir := filepath.Join(cfgDir, "services")
	if err := os.MkdirAll(servicesDir, 0755); err != nil {
		return fmt.Errorf("creating directory: %w", err)
	}

	// Generate TLS cert pair for kernel.yaml
	tlsChain, err := GenerateTLSCertChain()
	if err != nil {
		return fmt.Errorf("generating TLS cert chain: %w", err)
	}

	certB64 := tlsChain.Chain[0].Base64
	keyBytes, err := protoKey.KeyToYAML(tlsChain.Key)
	if err != nil {
		return fmt.Errorf("marshaling TLS key: %w", err)
	}
	keyB64 := base64.StdEncoding.EncodeToString(keyBytes)

	kernelContent := fmt.Sprintf(exampleKernelYAMLTemplate, certB64, keyB64)

	files := map[string]string{
		"kernel.yaml":    kernelContent,
		"sentinel.yaml":  exampleSentinelYAML,
		"gateway.yaml":   exampleGatewayYAML,
		"eventbus.yaml":  exampleEventbusYAML,
		"oauth.yaml": exampleOauthYAML,
		"graphdb.yaml":   exampleGraphdbYAML,
		"saml.yaml":      exampleSamlYAML,
		"opa.yaml":  exampleOpaYAML,
	}

	for relPath, content := range files {
		absPath := filepath.Join(servicesDir, relPath)
		if _, err := os.Stat(absPath); err == nil {
			fmt.Printf("  (exists, skipped) %s\n", relPath)
			continue
		}
		if err := os.WriteFile(absPath, []byte(content), 0644); err != nil {
			return fmt.Errorf("writing %s: %w", relPath, err)
		}
	}

	return nil
}

// InitOPA generates the OPA entitlements policy directory from the oauth config.
// It reads services/oauth.yaml to extract IDP provider issuers and generates
// trusted_issuer rules that validate the token's origin_iss claim.
// If oauth.yaml does not exist (oauth is disabled), it proceeds with an
// empty issuers list and prints a warning.
func InitOPA(cfgDir string) error {
	opaDir := OPAPolicyDir(cfgDir)

	var issuers []string

	oauthPath := filepath.Join(cfgDir, "services", "oauth.yaml")
	if _, err := os.Stat(oauthPath); err == nil {
		data, err := os.ReadFile(oauthPath)
		if err != nil {
			return fmt.Errorf("reading oauth config: %w", err)
		}

		var fwMap map[string]any
		if err := yaml.Unmarshal(data, &fwMap); err != nil {
			return fmt.Errorf("parsing oauth config: %w", err)
		}

		if providers, ok := fwMap["providers"].([]any); ok {
			for _, p := range providers {
				if pm, ok := p.(map[string]any); ok {
					if iss, ok := pm["issuer"].(string); ok && iss != "" {
						issuers = append(issuers, iss)
					}
				}
			}
		}
	} else {
		fmt.Printf("Warning: %s not found — generating default OPA policy with no trusted issuers.\n", oauthPath)
		fmt.Printf("  Add providers to services/oauth.yaml when oauth is configured and re-run init-opa.\n")
	}

	if err := WriteDefaultOPAPolicy(opaDir, issuers); err != nil {
		return fmt.Errorf("writing OPA policy: %w", err)
	}

	fmt.Printf("Generated OPA entitlements policy: %s/\n", opaDir)
	for _, iss := range issuers {
		fmt.Printf("  trusted issuer: %s\n", iss)
	}
	fmt.Printf("\nEdit services/opa/abac/attributes.rego to customize access rules.\n")
	fmt.Printf("Run 'cavalier-operator generate' to rebuild.\n")
	return nil
}

// WriteCreds generates credential pairs for all services and registers delegates.
func WriteCreds(cfgDir string) error {
	credsDir := filepath.Join(cfgDir, "creds")
	if err := os.MkdirAll(credsDir, 0755); err != nil {
		return fmt.Errorf("creating creds directory: %w", err)
	}

	kernelPath := filepath.Join(cfgDir, "services", "kernel.yaml")

	for _, name := range FrontendServiceNames {
		if err := writeCredPairAndDelegate(credsDir, kernelPath, name, name); err != nil {
			return err
		}
		if err := AddDelegate(kernelPath, name, "any", nil); err != nil {
			return fmt.Errorf("adding delegate for %s: %w", name, err)
		}
	}

	// Gateway — HTTP gateway, needs S2S access to backend services
	if err := writeCredPairAndDelegate(credsDir, kernelPath, "gateway", "any"); err != nil {
		return err
	}

	// TimeDB — needs S2S access (state registration)
	if err := writeCredPairAndDelegate(credsDir, kernelPath, "timedb", "any"); err != nil {
		return err
	}

	// Graphdb — graph database needs S2S access (state registration)
	if err := writeCredPairAndDelegate(credsDir, kernelPath, "graphdb", "any"); err != nil {
		return err
	}

	// Stratum — Supervisor LLM stateful SQL workspace, needs S2S access (state registration)
	if err := writeCredPairAndDelegate(credsDir, kernelPath, "stratum", "any"); err != nil {
		return err
	}

	// Keycloak secrets — generated once, never overwritten.
	if err := generateKeycloakSecrets(cfgDir); err != nil {
		return fmt.Errorf("generating keycloak secrets: %w", err)
	}

	return nil
}

// KeycloakSecrets holds auto-generated secrets for the Keycloak IDP service.
// Written to services/keycloak-generated.yaml; never overwritten once created.
type KeycloakSecrets struct {
	AdminPassword     string            `yaml:"admin_password"`
	OauthClientSecret string            `yaml:"oauth_client_secret"`
	UserPasswords     map[string]string `yaml:"user_passwords"`
}

// generateKeycloakSecrets creates services/keycloak-generated.yaml with random
// secrets. Idempotent — skips if the file already exists.
func generateKeycloakSecrets(cfgDir string) error {
	path := filepath.Join(cfgDir, "services", "keycloak-generated.yaml")
	if _, err := os.Stat(path); err == nil {
		return nil // already exists, keep existing secrets
	}

	randHex := func(n int) (string, error) {
		b := make([]byte, n)
		if _, err := rand.Read(b); err != nil {
			return "", err
		}
		return hex.EncodeToString(b), nil
	}

	adminPass, err := randHex(16) // 32 hex chars
	if err != nil {
		return fmt.Errorf("generating admin password: %w", err)
	}
	clientSecret, err := randHex(16)
	if err != nil {
		return fmt.Errorf("generating oauth client secret: %w", err)
	}
	adminUserPass, err := randHex(8) // 16 hex chars
	if err != nil {
		return fmt.Errorf("generating admin user password: %w", err)
	}
	joeuserPass, err := randHex(8)
	if err != nil {
		return fmt.Errorf("generating joeuser password: %w", err)
	}

	secrets := KeycloakSecrets{
		AdminPassword:     adminPass,
		OauthClientSecret: clientSecret,
		UserPasswords: map[string]string{
			"admin":   adminUserPass,
			"joeuser": joeuserPass,
		},
	}

	data, err := yaml.Marshal(secrets)
	if err != nil {
		return fmt.Errorf("marshaling keycloak secrets: %w", err)
	}
	if err := os.WriteFile(path, data, 0600); err != nil {
		return fmt.Errorf("writing keycloak-generated.yaml: %w", err)
	}
	fmt.Printf("  services/keycloak-generated.yaml (keycloak secrets generated)\n")
	return nil
}

// LoadKeycloakSecrets reads the auto-generated keycloak secrets from services/keycloak-generated.yaml.
// Returns an empty struct (no error) if the file does not exist.
func LoadKeycloakSecrets(cfgDir string) (*KeycloakSecrets, error) {
	path := filepath.Join(cfgDir, "services", "keycloak-generated.yaml")
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return &KeycloakSecrets{UserPasswords: map[string]string{}}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading keycloak-generated.yaml: %w", err)
	}
	var s KeycloakSecrets
	if err := yaml.Unmarshal(data, &s); err != nil {
		return nil, fmt.Errorf("parsing keycloak-generated.yaml: %w", err)
	}
	if s.UserPasswords == nil {
		s.UserPasswords = map[string]string{}
	}
	return &s, nil
}

// writeCredPairAndDelegate generates a cred pair for a service, writes it to disk,
// and adds a delegate entry to kernel.yaml.
func writeCredPairAndDelegate(credsDir, kernelPath, service, targetService string) error {
	credDir := filepath.Join(credsDir, service)
	if _, err := os.Stat(credDir); err == nil {
		fmt.Printf("  (exists, skipped) creds/%s/\n", service)
		return nil
	}

	if err := os.MkdirAll(credDir, 0755); err != nil {
		return fmt.Errorf("creating cred dir for %s: %w", service, err)
	}

	credPair, privateKey, err := GenerateCredPair()
	if err != nil {
		return fmt.Errorf("generating cred pair for %s: %w", service, err)
	}

	credBytes, err := protoJwk.JwkToYAML(credPair)
	if err != nil {
		return fmt.Errorf("marshaling cred pair for %s: %w", service, err)
	}
	if err := os.WriteFile(filepath.Join(credDir, "creds.yaml"), credBytes, 0644); err != nil {
		return fmt.Errorf("writing creds for %s: %w", service, err)
	}

	keyBytes, err := protoKey.KeyToYAML(privateKey)
	if err != nil {
		return fmt.Errorf("marshaling key for %s: %w", service, err)
	}
	if err := os.WriteFile(filepath.Join(credDir, "key.yaml"), keyBytes, 0600); err != nil {
		return fmt.Errorf("writing key for %s: %w", service, err)
	}

	if err := AddDelegate(kernelPath, service, targetService, nil); err != nil {
		return fmt.Errorf("adding delegate for %s: %w", service, err)
	}

	fmt.Printf("  creds/%s/ (delegate → %s)\n", service, targetService)
	return nil
}

// BuildKernelConfigProto reads the config directory and assembles the kernel Config proto.
func BuildKernelConfigProto(cfgDir string) (*protoKernel.Config, error) {
	servicesDir := filepath.Join(cfgDir, "services")

	// 1. Load kernel.yaml
	kernelCfg, err := LoadKernelSourceConfig(filepath.Join(servicesDir, "kernel.yaml"))
	if err != nil {
		return nil, err
	}

	// 2. Validate TLS key if present
	if kernelCfg.TLS != nil && kernelCfg.TLS.Key != "" {
		keyYAML, err := base64.StdEncoding.DecodeString(kernelCfg.TLS.Key)
		if err != nil {
			return nil, fmt.Errorf("decoding TLS key: %w", err)
		}
		_, err = protoKey.KeyFromBytes(keyYAML)
		if err != nil {
			return nil, fmt.Errorf("parsing TLS key: %w", err)
		}
	}

	// 3. Build delegates from source config + cred pairs.
	var delegates []*protoKernel.Delegate
	for _, sd := range kernelCfg.Delegates {
		var authSvcs []protoServices.ServiceName
		for _, s := range sd.AuthorizedServices {
			authSvcs = append(authSvcs, protoServices.ParseServiceNameLiberal(s))
		}
		delegate := &protoKernel.Delegate{
			Name:               sd.Name,
			AuthorizedServices: authSvcs,
		}
		// Find cred pair (Jwk) for this delegate
		credDir := filepath.Join(cfgDir, "creds", sd.Name)
		for _, ext := range []string{".yaml", ".json"} {
			p := filepath.Join(credDir, "creds"+ext)
			if data, err := os.ReadFile(p); err == nil {
				jwk, err := protoJwk.JwkFromBytes(data)
				if err == nil && jwk != nil {
					delegate.CredPairs = append(delegate.CredPairs, jwk)
				}
				break
			}
		}
		delegates = append(delegates, delegate)
	}

	// 4. Load per-service configs from separate files
	holder := &protoServicesConfig.Services{}
	hasHolder := false

	type serviceLoader struct {
		name string
		load func(map[string]any) error
	}
	loaders := []serviceLoader{
		{"sentinel", func(m map[string]any) error {
			cfg := &protoSentinel.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			holder.SentinelConfig = cfg
			hasHolder = true
			return nil
		}},
		{"gateway", func(m map[string]any) error {
			cfg := &protoGateway.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			protoGateway.ConfigDefaults(cfg)
			holder.GatewayConfig = cfg
			hasHolder = true
			return nil
		}},
		{"eventbus", func(m map[string]any) error {
			cfg := &protoEventbus.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			protoEventbus.ConfigDefaults(cfg)
			holder.EventbusConfig = cfg
			hasHolder = true
			return nil
		}},
		{"oauth", func(m map[string]any) error {
			cfg := &protoOauth.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			protoOauth.ConfigDefaults(cfg)
			holder.OauthConfig = cfg
			hasHolder = true
			return nil
		}},
		{"graphdb", func(m map[string]any) error {
			cfg := &protoGraphdb.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			protoGraphdb.ConfigDefaults(cfg)
			holder.GraphdbConfig = cfg
			hasHolder = true
			return nil
		}},
		{"msggateway", func(m map[string]any) error {
			cfg := &protoMsggateway.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}
			protoMsggateway.ConfigDefaults(cfg)
			holder.MsggatewayConfig = cfg
			hasHolder = true
			return nil
		}},
		{"opa", func(m map[string]any) error {
			delete(m, "entitlements_policy")
			delete(m, "backend_token_policy")

			cfg := &protoOpa.Config{}
			if err := unmarshalMapToProto(m, cfg); err != nil {
				return err
			}

			// Load OPA entitlements policy: prefer services/opa/ if present,
			// otherwise generate the default from IDP issuers in oauth.yaml.
			opaDir := OPAPolicyDir(cfgDir)
			if _, err := os.Stat(opaDir); err == nil {
				policy, err := LoadOPAPolicy(opaDir, "data.entitlements.eval")
				if err != nil {
					return fmt.Errorf("loading OPA entitlements policy: %w", err)
				}
				cfg.EntitlementsPolicy = policy
			} else {
				var idpIssuers []string
				oauthPath := filepath.Join(cfgDir, "services", "oauth.yaml")
				if fwData, err := os.ReadFile(oauthPath); err == nil {
					var fwMap map[string]any
					if err := yaml.Unmarshal(fwData, &fwMap); err == nil {
						if providers, ok := fwMap["providers"].([]any); ok {
							for _, p := range providers {
								if pm, ok := p.(map[string]any); ok {
									if iss, ok := pm["issuer"].(string); ok && iss != "" {
										idpIssuers = append(idpIssuers, iss)
									}
								}
							}
						}
					}
				}
				opaBundle := DefaultOPABundle(idpIssuers)
				cfg.EntitlementsPolicy = BuildOpaPolicy("data.entitlements.eval", opaBundle)
			}

			// Load OPA backend token policy from services/opa-backend-token/ if present.
			btDir := BackendTokenPolicyDir(cfgDir)
			if _, err := os.Stat(btDir); err == nil {
				btPolicy, err := LoadOPAPolicy(btDir, "data.backend_token.eval")
				if err != nil {
					return fmt.Errorf("loading OPA backend token policy: %w", err)
				}
				cfg.BackendTokenPolicy = btPolicy
			}

			holder.OpaConfig = cfg
			hasHolder = true
			return nil
		}},
	}

	for _, sl := range loaders {
		svcPath := filepath.Join(servicesDir, sl.name+".yaml")
		svcMap, err := loadServiceConfigFile(svcPath)
		if err != nil {
			continue
		}
		if len(svcMap) == 0 {
			if sl.name != "opa" {
				continue
			}
			svcMap = make(map[string]any)
		}
		if err := sl.load(svcMap); err != nil {
			return nil, fmt.Errorf("parsing %s config: %w", sl.name, err)
		}
	}

	// 5. Load operator config for FQDN/issuer
	opCfg, err := LoadConfig(cfgDir)
	if err != nil {
		opCfg = nil
	}

	fqdn := ""
	issuer := ""
	if opCfg != nil {
		fqdn = opCfg.Fqdn
		issuer = Issuer(opCfg)
	}

	// 5a. When dev=true, inject keycloak as an oauth provider and populate keycloak config.
	if opCfg != nil && opCfg.Dev {
		kcSecrets, err := LoadKeycloakSecrets(cfgDir)
		if err != nil {
			return nil, fmt.Errorf("loading keycloak secrets for oauth injection: %w", err)
		}
		if kcSecrets.OauthClientSecret != "" {
			realm := "cavalier"
			keycloakIssuer := fmt.Sprintf("https://%s/realms/%s", opCfg.Fqdn, realm)
			keycloakProvider := &protoOauth.ProviderConfig{
				Enable:       true,
				Name:         "Keycloak",
				Issuer:       keycloakIssuer,
				ClientId:     "cavalier",
				ClientSecret: kcSecrets.OauthClientSecret,
			}
			if holder.OauthConfig == nil {
				holder.OauthConfig = &protoOauth.Config{}
			}
			// Append keycloak provider (after any manually-configured providers).
			holder.OauthConfig.Providers = append(holder.OauthConfig.Providers, keycloakProvider)
			hasHolder = true
		}
		// Populate keycloak service config so kernel can serve it via GetConfig.
		if kcSecrets.AdminPassword != "" {
			kcCfg := &protoKeycloak.Config{
				AdminPassword:     kcSecrets.AdminPassword,
				OauthClientId:     "cavalier",
				OauthClientSecret: kcSecrets.OauthClientSecret,
				DefaultGroups:     []string{"admins", "users"},
				DefaultUsers: []*protoKeycloak.DefaultUser{
					{Username: "admin", Password: kcSecrets.UserPasswords["admin"], Groups: []string{"admins", "users"}},
					{Username: "joeuser", Password: kcSecrets.UserPasswords["joeuser"], Groups: []string{"users"}},
				},
			}
			protoKeycloak.ConfigDefaults(kcCfg)
			holder.KeycloakConfig = kcCfg
			hasHolder = true
		}
	}

	// 6. Build kernel Config proto
	kernelConfig := &protoKernel.Config{
		KeyRotationIntervalSeconds: kernelCfg.KeyRotationIntervalSeconds,
		DefaultTokenExpirySeconds:  kernelCfg.DefaultTokenExpirySeconds,
		Delegates:                  delegates,
		Fqdn:                       fqdn,
		Issuer:                     issuer,
	}
	protoKernel.ConfigDefaults(kernelConfig)
	if hasHolder {
		kernelConfig.Configs = holder
	}

	return kernelConfig, nil
}

// loadServiceConfigFile reads a per-service YAML config file into a map.
func loadServiceConfigFile(path string) (map[string]any, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var m map[string]any
	if err := yaml.Unmarshal(data, &m); err != nil {
		return nil, err
	}
	return m, nil
}

// unmarshalMapToProto converts a map[string]any to a proto message via JSON intermediate.
func unmarshalMapToProto(m map[string]any, target proto.Message) error {
	jsonBytes, err := json.Marshal(m)
	if err != nil {
		return fmt.Errorf("converting to JSON: %w", err)
	}
	if err := (protojson.UnmarshalOptions{DiscardUnknown: true}).Unmarshal(jsonBytes, target); err != nil {
		return fmt.Errorf("unmarshaling proto: %w", err)
	}
	return nil
}

// splitLines splits s by newlines and trims whitespace from each line.
func splitLines(s string) []string {
	return strings.Split(strings.TrimSpace(s), "\n")
}

// splitPath splits a path string by "/" separators.
func splitPath(s string) []string {
	return strings.Split(s, "/")
}

